function API_MUSICSEARCH(query) {
  if (query === undefined) {
    query = document.getElementById("MUSICSEARCH_BOX")?.value ?? "";
  }

  const table = document.getElementById("tablex");
  const body = table?.tBodies[0];
  if (!body) return;

  const search = String(query ?? "")
    .trim()
    .toLocaleLowerCase();
  Array.from(body.rows).forEach((row) => {
    const title = row.cells[0]?.textContent ?? "";
    row.style.display = title.toLocaleLowerCase().includes(search)
      ? "table-row"
      : "none";
  });
}

async function API_MUSIC_GET(id) {
  const table = document.getElementById("tablex");
  const audio = musicPlayer;

  if (!table || !audio) return;

  table.innerHTML = "";

  const identifier = id;

  try {
    /*
     * Get generated music metadata JSON
     *
     * Example:
     * id = "2022"
     *
     * → ./api/music/music-2022.json
     */
    const response = await fetch(`./api/music/music-${identifier}.json`);

    if (!response.ok) {
      throw new Error(`Music metadata failed: HTTP ${response.status}`);
    }

    const data = await response.json();

    if (!Array.isArray(data)) {
      console.error("Invalid music metadata JSON.");
      return;
    }

    const parent = table.tBodies[0] || table.createTBody();

    /*
     * Get each music entry
     */
    data.forEach((file) => {
      if (!file || typeof file !== "object") return;

      const title = file.title || "Unknown Title";
      const artist = file.artist || "";
      const album = file.album || "";
      const fileName = file.file || "";

      /*
       * Artwork generated by Node.js
       */
      const picture = "./api/music/" + file.picture || "";

      /*
       * Music file URL
       *
       * If the JSON is in:
       * ./api/music/music-2022.json
       *
       * and music is:
       * ./api/music/music-2022/Song.mp3
       *
       * then this resolves correctly.
       */
      const url = fileName
        ? `./api/music/music-${identifier}/${fileName
            .split("/")
            .map(encodeURIComponent)
            .join("/")}`
        : "";

      const format = fileName ? fileName.split(".").pop().toUpperCase() : "";

      /*
       * Create table row
       */
      const row = document.createElement("tr");

      row.className = "music_main";
      row.tabIndex = 0;
      row.style.display = "table-row";

      const cell = document.createElement("td");

      cell.colSpan = 3;
      cell.style.display = "table-cell";
      cell.id = "qwrknhqwq352sd";

      /*
       * Create music information line
       */
      const createLine = (icon, value, subtitle) => {
        const line = document.createElement("div");

        const main = document.createElement("span");

        main.innerHTML = `${icon} ${value}`;

        const small = document.createElement("small");

        small.textContent = subtitle;
        small.style.display = "block";

        line.append(main, small);

        return line;
      };

      cell.append(
        createLine(
          `<img src="./assets/icons/music.svg" width="12px" class="tint"/>`,
          title,
          artist,
        ),

        createLine("", album, format),
      );

      row.appendChild(cell);

      /*
       * Click → play
       */
      const play = async () => {
        if (!url || url === lastUrl) {
          return;
        }

        BLOB_LINK_SRC = null;
        lastUrl = url;

        AUDIOPLAYER_TITLE.textContent = title;
        AUDIOPLAYER_SUB.textContent = artist;

        /*
         * Media Session
         */
        if ("mediaSession" in navigator && navigator.mediaSession) {
          navigator.mediaSession.metadata = new MediaMetadata({
            title,
            artist,
            album,
            artwork: picture
              ? [
                  {
                    src: picture,
                    type: "image/webp",
                  },
                ]
              : [
                  {
                    src: "./assets/noalbum.svg",
                    type: "image/webp",
                  },
                ],
          });
        }

        document.getElementById("artwork").style.backgroundImage =
          picture.includes("null")
            ? `url('./assets/noalbum.svg')`
            : `url("${new URL(picture, document.baseURI).href}")`;

        fileformat = fileName;
        audio.src = url;
        audio.preload = "auto";
        audio.load();
        audio.play().catch(console.error);
        audio.playbackRate = window.SPEED_DEF;

        await new Promise((resolve) => setTimeout(resolve, 500));

        try {
          const response = await fetch(url);
          if (!response.ok) {
            alert(`Track download preparation failed: HTTP ${response.status}`);
            throw new Error(
              `Track download preparation failed: HTTP ${response.status}`,
            );
          } else {
            if (lastUrl) {
              BLOB_LINK_SRC = await response.blob();
              alert("The download is ready!");
            }
          }
        } catch (error) {
          alert(`Unable to prepare the track download: ${error}`);
          console.error("Unable to prepare the track download:", error);
        }
      };

      /*
       * Mouse
       */
      row.addEventListener("click", play);

      /*
       * Keyboard
       */
      row.addEventListener("keydown", (event) => {
        if (event.key === "Enter" || event.key === " ") {
          event.preventDefault();
          play();
        }
      });

      parent.appendChild(row);
    });
  } catch (error) {
    console.error("Unable to load music metadata:", error);
  }
}

