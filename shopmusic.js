function API_PLAYER_SCROLL() {
  const player = document.querySelector(".player");

  if (!player) return;

  const atBottom =
    window.innerHeight + window.scrollY >=
    document.documentElement.scrollHeight - 2;

  player.classList.toggle("at-bottom", atBottom);
}

